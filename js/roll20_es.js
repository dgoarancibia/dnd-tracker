  // "Hunter's Mark ◆" → "Marca del cazador"; "Channel Divinity (3 usos)" →
  // "Canalizar divinidad (3 usos)": se traduce la base y se deja el paréntesis.
  function nombre(n) {
    if (n == null) return n;
    const limpio = String(n).replace(/\s*[◆†○]/g, '').trim();
    const directo = _min[limpio.toLowerCase()];
    if (directo) return directo;
    const m = limpio.match(/^(.*?)\s*(\([^)]*\))$/);
    if (m) {
      const base = _min[m[1].toLowerCase()];
      if (base) return `${base} ${m[2]}`;
    }
    return limpio;
  }

  // Nombres de varias palabras dentro de un texto ("ventaja con Hunter's Mark").
  // Las de una sola palabra no se tocan: "Light" o "Shield" también son
  // propiedades y palabras sueltas, y se traducirían mal.
  let _re = null;
  function texto(t) {
    if (!t) return t;
    if (!_re) {
      const claves = Object.keys(NOMBRES).filter(k => /\s/.test(k))
        .sort((a, b) => b.length - a.length)
        .map(k => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
      _re = claves.length ? new RegExp(`\\b(${claves.join('|')})\\b`, 'gi') : null;
    }
    return _re ? String(t).replace(_re, x => _min[x.toLowerCase()] || x) : t;
  }

  return { nombre, texto };
